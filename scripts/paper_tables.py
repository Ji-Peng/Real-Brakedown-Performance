def run_pipeline(csv_dir, results_dir, selection_path, out_dir, strict=False,
                 claims_out=None, reference_derived=None):
    global CSV_DIR, RESULTS, SELECTION_PATH, OUT, CLAIMS_OUT, STRICT, REF_DERIVED
    global T, DERIVED, SIMD, STATUS_ROWS, CLAIMS_ROWS, SEL_DATA

    CSV_DIR = pathlib.Path(csv_dir)
    RESULTS = pathlib.Path(results_dir)
    SELECTION_PATH = pathlib.Path(selection_path) if selection_path else (RESULTS / "selection.json")
    OUT = pathlib.Path(out_dir)
    CLAIMS_OUT = pathlib.Path(claims_out) if claims_out else None
    STRICT = bool(strict)
    REF_DERIVED = load_reference_derived(reference_derived or DEFAULT_REF_DERIVED)

    DERIVED = []
    SIMD = {}
    STATUS_ROWS = []
    CLAIMS_ROWS = []
    SEL_DATA = json.loads(SELECTION_PATH.read_text(encoding="utf-8")) if SELECTION_PATH.is_file() else {}

    T = {k: Table(v, CSV_DIR) for k, v in {
        "T0": "table_T0_correctness", "T1": "table_T1_headline_encoding",
        "T2": "table_T2_simd_spielman", "T3": "table_T3_steps_breakdown",
        "T4": "table_T4_slice_sweep", "T5": "table_T5_field_comparison",
        "T6": "table_T6_pcs_breakdown", "T7": "table_T7_verifier_encoding",
        "T8": "table_T8_setup_memory", "T9": "table_T9_orion_shape",
        "T10": "table_T10_brakedown_vs_rs",
        "T11": "table_T11_codegen_evidence", "T12": "table_T12_arm_portability",
        "F2": "figure_F2_llc_scaling_data", "F3": "figure_F3_thread_scaling_data",
        "DIV": "session_divergence", "TODO": "todo_cells", "STATS": "cell_statistics",
    }.items()}

    check_inputs()
    OUT.mkdir(parents=True, exist_ok=True)
    write_hosts_tex()
    D = derive()
    tab_platforms()
    tab_headline(D)
    tab_steps()
    tab_simd()
    tab_pcs(D)
    tab_correctness()
    tab_codegen()
    tab_fields()
    tab_slices()
    tab_arm()
    tab_setup()
    ok = fig_threads()
    ok2 = fig_llc()
    write_csv("paper_tables_status.csv", ["table", "status", "reason"], STATUS_ROWS, None)
    hard_ok = evaluate_claims(D)
    print(f"wrote {len(list(OUT.glob('tab_*.tex')))} paper tables, {len(DERIVED)} derived values, "
          f"{len(CLAIMS_ROWS)} claim checks"
          + (", fig_threads.pdf" if ok else "") + (", fig_llc.pdf" if ok2 else "") + f" to {OUT}")
    return hard_ok


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--csv-dir", default="analysis/csv", help="Directory containing analyze.py CSV outputs")
    parser.add_argument("--results-dir", default="results", help="Results root directory containing manifests")
    parser.add_argument("--selection", default=None, help="Selection JSON path (default: <results-dir>/selection.json)")
    parser.add_argument("--out-dir", default="out/paper", help="Output directory for paper tables and figures")
    parser.add_argument("--claims-out", default=None, help="Optional extra path to copy claims.csv")
    parser.add_argument("--reference-derived", default=str(DEFAULT_REF_DERIVED),
                        help="Archived derived.csv used as reference ranges in claims.csv")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--strict", action="store_true", help="Fatal assertions on all paper expectations")
    mode.add_argument("--lenient", action="store_true", help="Tolerate missing claims/hosts/sizes (default)")
    args = parser.parse_args()

    hard_ok = run_pipeline(
        csv_dir=args.csv_dir,
        results_dir=args.results_dir,
        selection_path=args.selection,
        out_dir=args.out_dir,
        strict=args.strict,
        claims_out=args.claims_out,
        reference_derived=args.reference_derived,
    )
    if not hard_ok:
        print("[FAIL] Hard claim check (C0 or C1) FAILED; see claims.csv", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
