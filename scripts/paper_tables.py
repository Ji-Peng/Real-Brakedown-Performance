def x86_hosts():
    hs = T["T1"].hosts() if "T1" in T else []
    if not hs and "T11" in T:
        hs = [h for h in T["T11"].hosts() if h not in arm_hosts_list()]
    if not hs and SEL_DATA:
        for h, cfg in SEL_DATA.get("machines", {}).items():
            if "aarch64" not in str(cfg.get("role", "")).lower() and h not in arm_hosts_list():
                hs.append(h)
    return hs


def arm_hosts_list():
    if "T12" not in T or T["T12"].is_not_run_placeholder():
        return []
    hosts = T["T12"].hosts()
    if not hosts:
        seen = []
        for d in T["T12"].dicts():
            h = d.get("Host")
            if h and h not in seen and not NOT_RUN_RE.match(h) and h != "-":
                seen.append(h)
        return seen
    return hosts


def arm_hosts():
    """(main, second) AArch64 hosts of T12 (strict mode requires two)."""
    hs = arm_hosts_list()
    if not STRICT:
        return tuple(hs)
    xh = x86_hosts()
    main_fork = T["T1"].forks(xh[0]) if xh else set()
    same = [h for h in hs if T["T12"].forks(h) == main_fork]
    other = [h for h in hs if h not in same]
    if len(same) != 1 or len(other) != 1:
        sys.exit(f"T12: expected one AArch64 host at the T1 fork commit {main_fork} and one other, "
                 f"found {same} and {other}")
    return same[0], other[0]


def arm2_fork():
    hs = arm_hosts()
    if len(hs) < 2:
        return None
    forks = {f.split("+")[0] for f in T["T12"].forks(hs[1])}
    if STRICT and len(forks) != 1:
        sys.exit(f"T12: expected one fork commit for the second AArch64 host, found {forks}")
    return sorted(forks)[0] if forks else None


def detect_mt_threads():
    if SEL_DATA.get("mt_threads"):
        return str(int(SEL_DATA["mt_threads"]))
    ts = set()
    for tab_key, col in (("T1", "T"), ("T6", "T"), ("T12", "Threads")):
        if tab_key in T:
            for d in T[tab_key].dicts():
                if d.get(col, "").isdigit() and int(d[col]) > 1:
                    ts.add(int(d[col]))
    return str(max(ts)) if ts else "8"


def check_inputs():
    if not STRICT:
        return
    expected = {"T1": 14, "T2": 42, "T3": 20, "T4": 6, "T5": 4, "T9": 42, "T12": 12}
    for k, n in expected.items():
        if len(T[k].rows) != n:
            sys.exit(f"{k}: expected {n} rows, found {len(T[k].rows)}")
    for d in T["T1"].dicts():
        for c in ("Significance vs as-published-as-is", "Significance vs fork-flags-portable",
                  "Significance vs PolyCommit"):
            if d[c] != "faster":
                sys.exit(f"T1 {d['log2(N)']},{d['T']} {c} = {d[c]!r}, expected 'faster'")
    for d in T["T11"].dicts():
        if d["Vector Arith"] != "0" or d["Scalar Status"] != "PASS":
            sys.exit(f"T11 row {d} has vector arithmetic or is not PASS")
    for d in T["T0"].dicts():
        if not d["Status"].startswith("PASS"):
            sys.exit(f"T0 check {d['Gate / Invariant']} is not PASS")
    for d in T["TODO"].dicts():
        if not d["Status"].startswith("omitted"):
            sys.exit(f"todo_cells.csv: {d['Cell']} is {d['Status']!r}")
    if len(T["T1"].hosts()) != 1 or len(T["T12"].hosts()) != 2:
        sys.exit(f"expected one x86-64 host in T1 and two AArch64 hosts in T12, found "
                 f"{T['T1'].hosts()} and {T['T12'].hosts()}")
    arm_hosts()


