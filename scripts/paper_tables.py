def simd_cell(shape, d):
    twcol = "This Work (ms)" if shape == "bd" else "This Work Orion (ms)"
    t1col = "SIMD-Spielman T workers (ms)" if shape == "bd" else "SIMD-Spielman Orion T workers (ms)"
    simdcol = t1col if d["T"] == "1" else "SIMD best-of-T incl. T=1 (ms)"
    tw, simd = d.get(twcol, ""), d.get(simdcol, "")
    for c in (tw, simd):
        if c.startswith("omitted"):
            return "o", None, ""
        if lead(c) is None:
            return "--", None, ""
    r = num(split_div(tw)[0]) / num(split_div(simd)[0])
    v = f2(r)
    if d["T"] != "1" and d.get("SIMD MT slower than its T=1") == "yes":
        v += "*"
    if is_div(tw) or is_div(simd):
        v += DAGGER
    src = f"{twcol}={lead(tw)} / {simdcol}={lead(simd)}"
    return v, r, src


