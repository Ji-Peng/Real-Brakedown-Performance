"""Generate compact paper tables, figures, derived values, and claims verdicts.

Reads the CSV outputs of scripts/analyze.py and block manifests under a results
tree, and writes:
  - tab_<name>.tex / tab_<name>.csv   (tabularray talltblr with booktabs rules)
  - derived.tex / derived.csv         (\\derived{key} values with formula & sources)
  - hosts.tex                         (host macro bindings for lenient fresh runs)
  - fig_threads.pdf, fig_llc.pdf      (matplotlib figures)
  - paper_tables_status.csv           (per-table generated / skipped status)
  - claims.csv                        (per-claim PASS / DIFFERS / NOT-RUN / FAIL)

Modes:
  --strict   Every paper expectation (complete grids, all T1 faster, 1 x86-64
             host + 2 AArch64 hosts, zero vector arithmetic, all T0 PASS) is a
             fatal assertion.
  --lenient  (default) Adapts to whatever hosts, sizes, threads, and claims
             exist in the results tree; skipped tables are recorded in
             paper_tables_status.csv and claim outcomes in claims.csv.
             Hard claims (C0 correctness, C1 scalar codegen) still cause a
             non-zero exit on FAIL.
"""

