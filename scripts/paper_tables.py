def selected_manifests(host):
    runs = SEL_DATA.get("machines", {}).get(host, {}).get("runs", [])
    out, sessions = [], set()
    hostdir = RESULTS / host
    if not hostdir.is_dir():
        return out, sessions
    for run in runs:
        for rd in sorted(hostdir.iterdir()):
            if not rd.is_dir() or not fnmatch.fnmatch(rd.name, run["run_dir"]):
                continue
            for sess in run["sessions"]:
                if (rd / sess).is_dir():
                    sessions.add(sess)
                for mf in sorted((rd / sess).glob("**/manifest.json")):
                    try:
                        out.append(json.loads(mf.read_text(encoding="utf-8")))
                    except (OSError, ValueError):
                        pass
    return out, sessions


def g(d, *path):
    for p in path:
        if not isinstance(d, dict) or p not in d:
            return None
        d = d[p]
    return d


def distinct(ms, *path):
    vals = []
    for m in ms:
        v = g(m, *path)
        if v not in (None, "", []) and v not in vals:
            vals.append(v)
    return vals


def kib(s):
    m = re.match(r"(\d+)\s*([KMG])", str(s))
    if not m:
        return None
    return int(m.group(1)) * {"K": 1, "M": 1024, "G": 1024 ** 2}[m.group(2)]


def size_str(k):
    return f"{k // 1024}~MiB" if k >= 1024 else f"{k}~KiB"


def platform_facts(host):
    ms, sessions = selected_manifests(host)
    todo = lambda what: (r"\todo{" + what + "}" if STRICT else "not reported")  # noqa: E731

    def one(vals, what, fmt=lambda v: esc(str(v))):
        return ", ".join(fmt(v) for v in vals) if vals else todo(what)

    caches = {}
    for m in ms:
        for c in g(m, "cache_topology") or []:
            k = (c.get("level"), c.get("type"))
            if k not in caches and kib(c.get("size")):
                caches[k] = kib(c["size"])
    flags = " ".join(l for m in ms for l in (g(m, "cpu", "lscpu") or "").splitlines()
                     if l.startswith("Flags"))
    cores = [len(c) for c in distinct(ms, "pinning", "affinity_cores_expanded")
             if isinstance(c, list)]
    models = distinct(ms, "cpu", "model_name") or [
        l.split(":", 1)[1].strip() for m in ms[:1]
        for l in (g(m, "cpu", "lscpu") or "").splitlines() if l.startswith("Model name:")]
    mem = [int(re.match(r"\d+", v).group(0)) for v in distinct(ms, "memory", "MemTotal")
           if re.match(r"\d+", str(v))]
    gxx = [re.search(r"(\d+\.\d+\.\d+)\s*$", v).group(1) for v in
           distinct(ms, "compilers_simd_spielman", "gxx_version") if re.search(r"(\d+\.\d+\.\d+)\s*$", v)]
    gov = [v for v in distinct(ms, "frequency_turbo", "scaling_governor")]
    rustc = distinct(ms, "rust_toolchain", "rustc_verbose", "release")
    vm_type = distinct(ms, "machine_identity", "gcp_machine_type")
    llvm = distinct(ms, "rust_toolchain", "rustc_verbose", "LLVM version")
    return {
        "Node class": (one(vm_type, "VM type") + " VM" if vm_type
                       else esc(host[4:] if host.startswith("soc-") else host)),
        "CPU": one(models, "CPU model"),
        "Cores used": str(max(cores)) if cores else todo("cores"),
        "L1d / L2 per core": (f"{size_str(caches[('1', 'Data')])} / {size_str(caches[('2', 'Unified')])}"
                              if ("1", "Data") in caches and ("2", "Unified") in caches
                              else todo("L1d/L2")),
        "L3 per domain": (size_str(caches[("3", "Unified")]) if ("3", "Unified") in caches
                          else ("not reported" if ms else todo("L3 size"))),
        "Memory": (f"{round(max(mem) / 1024 ** 2)}~GiB" if mem else todo("memory")),
        "AVX-512 IFMA": ("yes" if "avx512ifma" in flags else "no") if flags else todo("IFMA"),
        "Governor": one(gov, "governor") if gov or not ms else "not reported",
        "OS": one(distinct(ms, "os_and_kernel", "PRETTY_NAME"), "OS"),
        "Kernel": one(distinct(ms, "os_and_kernel", "kernel_release"), "kernel"),
        "glibc": one(distinct(ms, "os_and_kernel", "glibc_version"), "glibc"),
        "rustc / LLVM": (f"{', '.join(rustc)} / {', '.join(llvm)}" if rustc and llvm
                         else todo("rustc/LLVM")),
        "g++": ", ".join(gxx) if gxx else "--",
        "Sessions": str(len(sessions)) if sessions else todo("sessions"),
    }, ms


def build_facts(ms):
    todo = lambda what: (r"\todo{" + what + "}" if STRICT else "--")  # noqa: E731

    def flags_desc(fl):
        fl = " ".join(fl) if isinstance(fl, list) else (fl or "")
        if fl.strip() in ("", "Cargo defaults"):
            return "no flags, vectorizers on"
        parts = []
        if "target-cpu=native" in fl:
            parts.append(r"\code{native}")
        parts.append("vectorizers off" if "no-vectorize-loops" in fl and "no-vectorize-slp" in fl
                     else "vectorizers on")
        return ", ".join(parts)

    profile = {"tw-release": "fat LTO", "fork-release": "fat LTO", "release": "default profile"}

    def blake(features):
        if not features:
            return todo("BLAKE3 features")
        return "portable" if "pure" in features else "SIMD dispatch"

    tw = next((m for m in ms if g(m, "benchmark_parameters", "params_mode") and
               g(m, "extra", "baseline") is None and g(m, "extra", "upstream_commit") is None
               and g(m, "rust_toolchain", "effective_rustflags") is not None), None)
    lc = next((m for m in ms if g(m, "extra", "baseline", "variants")), None)
    pc = next((m for m in ms if str(g(m, "extra", "baseline", "implementation") or "")
               .startswith("arkworks")), None)
    sd = next((m for m in ms if g(m, "extra", "upstream_compile_flags")), None)
    rows = []
    rows.append([r"{\thiswork}", r"both", r"{\Mont}, {\Mers}, {\Fptwo}",
                 (profile["tw-release"] + ", " + flags_desc(g(tw, "rust_toolchain", "effective_rustflags"))
                  if tw else todo("build")), "portable"])
    for key, name in (("as-published-as-is", r"{\lcpcpub}"), ("fork-flags-portable", r"{\lcpcff}")):
        v = g(lc, "extra", "baseline", "variants", key)
        if v or STRICT:
            rows.append([name, r"{\lcpccode}", r"{\Ftlcpc}",
                         (profile.get(v.get("cargo_profile"), esc(str(v.get("cargo_profile")))) + ", "
                          + flags_desc(v.get("effective_rustflags", v.get("rustflags")))) if v
                         else todo("build"),
                         blake(v.get("blake3_features")) if v else todo("hash")])
    pcb = g(pc, "extra", "baseline", "build")
    if pcb or STRICT:
        rows.append([r"{\polycommit}", "own, shorter",
                     r"{\Mont}" if g(pc, "benchmark_parameters", "field") == "Mont127" else todo("field"),
                     (profile.get(pcb.get("cargo_profile"), esc(str(pcb.get("cargo_profile")))) + ", "
                      + flags_desc(pcb.get("effective_rustflags"))) if pcb else todo("PolyCommit build"),
                     "none"])
    if sd or STRICT:
        if sd:
            fl = g(sd, "extra", "upstream_compile_flags").split(";")[0].split()
            keep = [f for f in fl if f in ("-O3", "-march=native")]
            sdb = r"\code{" + " ".join(keep) + "}, AVX-512"
        else:
            sdb = todo("build")
        rows.append([r"{\simdsp}", r"{\simdcode}", r"{\Mont}, {\Mers}, {\Fptwo}", sdb, "none"])
    return rows


