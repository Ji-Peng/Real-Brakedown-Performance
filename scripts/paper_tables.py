def _plt():
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception as e:
        print(f"warning: matplotlib unavailable ({e}); figures not written")
        return None
    plt.rcParams.update({"font.size": 8, "font.family": "sans-serif", "axes.linewidth": 0.6,
                         "pdf.fonttype": 42})
    return plt


def fig_threads():
    f3 = T["F3"].dicts()
    if not f3:
        record_status("fig_threads", "skipped", "no thread-scaling data (F3)")
        return False
    plt = _plt()
    if plt is None:
        record_status("fig_threads", "skipped", "matplotlib unavailable")
        return False
    series = [("This Work", "RBP-LCPC", "#2a78d6", "-", "o"),
              ("LCPC as-published-as-is", "LCPC-default", "#eb6834", "--", "s"),
              ("LCPC fork-flags-portable", "LCPC-tuned", "#1baf7a", ":", "^")]
    logs = sorted({d["log2(N)"] for d in f3}, key=int)
    tmax = max(int(d["T"]) for d in f3)
    ticks = sorted({int(d["T"]) for d in f3})
    fig, axes = plt.subplots(1, len(logs), figsize=(max(3.2, 1.575 * len(logs)), 2.1), sharey=True)
    if len(logs) == 1:
        axes = [axes]
    for ax, l in zip(axes, logs):
        ax.plot([1, tmax], [1, tmax], color="#9a9a96", lw=0.8, ls=(0, (1, 2)), zorder=1, label="ideal")
        for key, lab, col, ls, mk in series:
            pts = sorted((int(d["T"]), float(d["Speedup"])) for d in f3
                         if d["Series"] == key and d["log2(N)"] == l)
            if pts:
                ax.plot([p[0] for p in pts], [p[1] for p in pts], color=col, ls=ls, lw=1.6,
                        marker=mk, ms=4, label=lab, zorder=3)
        ax.set_title(f"$N=2^{{{l}}}$", fontsize=8)
        ax.set_xticks(ticks)
        ax.set_xlim(0.6, tmax + 0.6)
        ax.set_ylim(0.6, tmax + 0.6)
        ax.grid(True, color="#e6e6e3", lw=0.5)
        ax.set_axisbelow(True)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
        ax.set_xlabel("Threads $T$")
    axes[0].set_ylabel("Speedup $t(1)/t(T)$")
    h, lab = axes[0].get_legend_handles_labels()
    fig.legend(h, lab, loc="upper center", ncol=4, frameon=False, bbox_to_anchor=(0.5, 1.04))
    fig.tight_layout(rect=(0, 0, 1, 0.9))
    OUT.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / "fig_threads.pdf", metadata={"CreationDate": None})
    plt.close(fig)
    record_status("fig_threads", "generated")
    return True


