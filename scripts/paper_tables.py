class Table:
    """One generated CSV: title, provenance, notes, header and rows (strings)."""

    def __init__(self, stem, csv_dir=None):
        self.stem = stem
        self.path = (csv_dir or CSV_DIR) / f"{stem}.csv"
        self.exists = self.path.is_file()
        self.title = None
        self.provenance = None
        self.notes = []
        self.header = []
        self.rows = []
        if not self.exists:
            return
        data = []
        for line in self.path.read_text(encoding="utf-8").splitlines():
            s = line.strip()
            if s.startswith('"#'):
                text = next(csv.reader([s]))[0]
            elif s.startswith("#"):
                text = s
            else:
                if s:
                    data.append(line)
                continue
            text = text[1:].strip()
            if text.startswith("Provenance:"):
                self.provenance = text[len("Provenance:"):].strip()
            elif text.startswith("Note:"):
                self.notes.append(text[len("Note:"):].strip())
            elif text.startswith("Key columns:"):
                pass
            elif self.title is None:
                self.title = text
        if not data:
            return
        rows = list(csv.reader(data))
        self.header = rows[0]
        self.rows = [r for r in rows[1:] if r]
        for r in self.rows:
            if len(r) != len(self.header):
                sys.exit(f"{self.path}: row with {len(r)} cells, header has {len(self.header)}")

    def is_not_run_placeholder(self):
        if not self.exists or not self.rows:
            return True
        return all(all(NOT_RUN_RE.match(c.strip()) for c in r) for r in self.rows)

    def not_run_reason(self):
        if not self.exists:
            return f"missing {self.stem}.csv"
        if not self.rows:
            return "no measured rows"
        for r in self.rows:
            for c in r:
                m = NOT_RUN_RE.match(c.strip())
                if m:
                    return m.group(1)
        return "inputs absent"

    def dicts(self):
        if self.is_not_run_placeholder():
            return []
        return [dict(zip(self.header, r)) for r in self.rows]

    def find(self, **keys):
        hits = [d for d in self.dicts() if all(d.get(k) == v for k, v in keys.items())]
        if len(hits) != 1:
            sys.exit(f"{self.stem}: expected one row for {keys}, found {len(hits)}")
        return hits[0]

    def find_opt(self, **keys):
        hits = [d for d in self.dicts() if all(d.get(k) == v for k, v in keys.items())]
        return hits[0] if len(hits) == 1 else None

    def runs(self):
        out = []
        for m in re.finditer(
            r"([A-Za-z0-9_.-]+)/(\d{4}-\d\d-\d\d-[A-Za-z0-9_-]+)/([A-Za-z0-9_-]+) \(",
            self.provenance or "",
        ):
            if m.groups() not in out:
                out.append(m.groups())
        return out

    def hosts(self):
        out = []
        for h, _, _ in self.runs():
            if h not in out:
                out.append(h)
        return out

    def forks(self, host):
        out = set()
        for m in re.finditer(
            r"([A-Za-z0-9_.-]+)/\d{4}-\d\d-\d\d-[A-Za-z0-9_-]+/[A-Za-z0-9_-]+ \(fork ([^,)]+)",
            self.provenance or "",
        ):
            if m.group(1) == host:
                out.update(m.group(2).split("/"))
        return out


def split_div(cell):
    m = DIV_RE.search(cell)
    if m:
        return cell[: m.start()], m.group(1)
    return cell, None


def lead(cell):
    m = NUM_RE.match(str(cell).strip())
    return m.group(0) if m else None


def num(cell):
    v = lead(cell)
    if v is None:
        sys.exit(f"not a number: {cell!r}")
    return float(v)


def num_opt(cell):
    v = lead(cell)
    return float(v) if v is not None else None


def is_div(cell):
    return split_div(str(cell).strip())[1] is not None


def esc(s):
    s = str(s).replace("--", "\x00")
    out = "".join(_ESC.get(ch, ch) for ch in s).replace("\x00", "-{}-")
    bad = [ch for ch in out if ord(ch) > 127]
    if bad:
        sys.exit(f"unhandled non-ASCII characters {bad!r} in {s!r}")
    return out


def tex(s):
    out = esc(s)
    for old, new in _NAMES:
        out = out.replace(esc(old), new)
    return out


def cell_val(cell, dagger=True):
    base, div = split_div(str(cell).strip())
    if base.startswith("N/A") or NOT_RUN_RE.match(base):
        return "--"
    if base.startswith("omitted"):
        return "o"
    v = lead(base)
    if v is None:
        return tex(base)
    return v + (DAGGER if (div and dagger) else "")


def write(name, text, inputs):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(HEADER.format(inputs=inputs) + text, encoding="utf-8")


def write_csv(name, header, rows, inputs, path=None):
    target = path or (OUT / name)
    target.parent.mkdir(parents=True, exist_ok=True)
    with open(target, "w", newline="", encoding="utf-8") as f:
        if inputs is not None:
            f.write(f"# Generated by scripts/paper_tables.py from {inputs}; do not edit.\n")
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows([[str(c).replace(DAGGER, " (divergent)") for c in r] for r in rows])


def selection_sha():
    if SELECTION_PATH and SELECTION_PATH.is_file():
        return hashlib.sha256(SELECTION_PATH.read_bytes()).hexdigest()[:12]
    return "none"


def source_comment(tabs):
    lines = [
        "% Source: " + "; ".join(f"generated/csv/{t.stem}.csv" for t in tabs)
        + f"; results/selection.json sha256 {selection_sha()}"
    ]
    for t in tabs:
        for h, r, s in t.runs():
            lines.append(f"%   {t.stem}: {h}/{r}/{s}")
    return "\n".join(lines) + "\n"


def span(n, text, align="c"):
    return [rf"\SetCell[c={n}]{{{align}}} {text}"] + [""] * (n - 1)


def tblr(label, caption, colspec, head, rows, note=None, remarks=(), size=r"\footnotesize",
         placement="tbp", colsep=None, width=None, src=""):
    outer = [f"  caption = {{{caption}}},", f"  label = {{{label}}},"]
    if note:
        outer.append(f"  remark{{Note}} = {{{note}}},")
    body = "\n".join(r if isinstance(r, str) else " & ".join(r) for r in rows)
    for sym, text in remarks:
        if sym not in body:
            continue
        outer.append(f"  remark{{{sym}}} = {{{text}}},")
    inner = [f"  colspec = {{{colspec}}},", f"  cells = {{font={size}}},"]
    if colsep:
        inner.append(f"  colsep = {colsep},")
    if width:
        inner.append(f"  width = {width},")
    out = [src.rstrip("\n"), f"\\begin{{table}}[{placement}]", r"\centering",
           r"\begin{talltblr}["] + outer + [r"]{"] + inner + [r"}", r"\toprule"]

    def emit(r):
        out.append(r if isinstance(r, str) else " & ".join(r) + r" \\")

    for r in head:
        emit(r)
    out.append(r"\midrule")
    for r in rows:
        emit(r)
    out += [r"\bottomrule", r"\end{talltblr}", r"\end{table}", ""]
    return "\n".join(x for x in out if x != "")


