def ref_range(key_prefix, suffix=""):
    """Archived range string from scripts/paper_reference/derived.csv, never hand-typed."""
    lo = REF_DERIVED.get(f"{key_prefix}-min")
    hi = REF_DERIVED.get(f"{key_prefix}-max")
    if lo is not None and hi is not None:
        return f"{lo}-{hi}{suffix}" if lo != hi else f"{lo}{suffix}"
    val = REF_DERIVED.get(key_prefix)
    return f"{val}{suffix}" if val is not None else "n/a"


def load_reference_derived(path):
    out = {}
    if not path or not pathlib.Path(path).is_file():
        return out
    with open(path, "r", encoding="utf-8", newline="") as f:
        rows = [r for r in csv.reader(f) if r and not r[0].startswith("#")]
    if len(rows) < 2:
        return out
    for r in rows[1:]:
        if len(r) >= 2:
            out[r[0]] = r[1]
    return out


